#!/usr/bin/env python3
"""Assemble the publishable site folder from web/ sources plus a computed leaderboard.json.

Output (flat, so the page URLs never change):
  index.html, leaderboard.html        the leaderboard page (two names, same page)
  leaderboard.json                    the data (schema: docs/SCHEMA.md)
  leaderboard_basic.html              plain no-JavaScript table
  sbffc-leaderboard.css / .js         page styling and code
  squarespace-code-block.txt          copy/paste snippet for a Squarespace Code Block (points at public_url)
  snippet-test.html                   the same snippet inside a fake Squarespace page (for testing)
  .nojekyll
"""
import os, re, shutil

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WEB = os.path.join(REPO, "web")


def _display_attrs(html, display):
    tz = display.get("timezone", "America/Chicago")
    refresh = int(display.get("auto_refresh_seconds", 300))
    places = int(display.get("prize_places", 21))
    html = re.sub(r'data-timezone="[^"]*"', f'data-timezone="{tz}"', html)
    html = re.sub(r'data-refresh="[^"]*"', f'data-refresh="{refresh}"', html)
    html = re.sub(r'data-prize-places="[^"]*"', f'data-prize-places="{places}"', html)
    return html


def snippet(json_url, display):
    css = open(os.path.join(WEB, "sbffc-leaderboard.css")).read()
    js = open(os.path.join(WEB, "sbffc-leaderboard.js")).read()
    assert "</script" not in js.lower() and "</style" not in css.lower()
    s = f"""<!-- SBFFC Leaderboard - Squarespace Code Block (Mode: HTML). JavaScript in Code Blocks needs a Core, Plus or Advanced plan.
     data-src = the published leaderboard.json. Generated by src/build_site.py - edit web/* and rebuild rather than editing this. -->
<div class="sbffc-lb" data-sbffc-leaderboard
     data-src="{json_url}"
     data-timezone="America/Chicago" data-refresh="300" data-prize-places="21" data-view="championship"></div>
<style>
{css}
</style>
<script>
{js}
</script>
"""
    return _display_attrs(s, display)


SNIPPET_TEST = """<!doctype html><html><head><meta charset="utf-8"><meta name=viewport content="width=device-width,initial-scale=1">
<title>SBFFC snippet test (simulated Squarespace page)</title><link rel="icon" href="data:,">
<link href="https://fonts.googleapis.com/css2?family=Audiowide&family=Barlow+Condensed:wght@400;500;600;700&display=swap" rel="stylesheet">
<style>:root{--body-font-font-family:"Barlow Condensed";--heading-font-font-family:"Audiowide"}
body{margin:0;font-family:Georgia,serif;background:#fff} table td{border:3px solid lime} button{background:yellow;border-radius:20px} h2{color:green;text-transform:uppercase}
.fake-nav{background:#000;color:#fff;padding:30px;font-family:Audiowide} .content-wrapper{max-width:1200px;margin:0 auto;padding:40px 4vw}</style></head>
<body><div class=fake-nav>Squarespace page header (simulated) - hostile global CSS applied to test scoping</div>
<div class=content-wrapper><div class="sqs-block code-block"><div class="sqs-block-content">__SNIPPET__</div></div></div></body></html>
"""


def assemble(site_dir, data_dir, display=None, public_url=None):
    """Copy web/ + data into site_dir. data_dir holds leaderboard.json and leaderboard_basic.html."""
    display = display or {}
    os.makedirs(site_dir, exist_ok=True)
    page = _display_attrs(open(os.path.join(WEB, "index.html")).read(), display)
    for name in ("index.html", "leaderboard.html"):
        with open(os.path.join(site_dir, name), "w") as f: f.write(page)
    for name in ("sbffc-leaderboard.css", "sbffc-leaderboard.js"):
        shutil.copy(os.path.join(WEB, name), os.path.join(site_dir, name))
    for name in ("leaderboard.json", "leaderboard_basic.html"):
        shutil.copy(os.path.join(data_dir, name), os.path.join(site_dir, name))
    open(os.path.join(site_dir, ".nojekyll"), "w").close()
    url = (public_url or "https://YOUR-GITHUB-USER.github.io/sbffc-leaderboard/").rstrip("/") + "/leaderboard.json"
    with open(os.path.join(site_dir, "squarespace-code-block.txt"), "w") as f: f.write(snippet(url, display))
    with open(os.path.join(site_dir, "snippet-test.html"), "w") as f:
        f.write(SNIPPET_TEST.replace("__SNIPPET__", snippet("leaderboard.json", display)))
    return sorted(os.listdir(site_dir))
